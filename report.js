function downloadPDF(){

const { jsPDF } = window.jspdf;

let doc = new jsPDF();


let project = document.getElementById("project").value;
let client = document.getElementById("client").value;
let engineer = document.getElementById("engineer").value;
let date = document.getElementById("date").value;
let details = document.getElementById("details").value;


// Header

doc.setFontSize(18);
doc.text("THE SR HOMES", 20, 20);

doc.setFontSize(12);
doc.text("Structural Engineering & Quantity Solutions", 20, 30);


doc.line(20,35,190,35);


// Details

doc.setFontSize(12);

doc.text("ENGINEERING REPORT",20,50);


doc.text("Project: " + project,20,65);

doc.text("Client: " + client,20,75);

doc.text("Engineer: " + engineer,20,85);

doc.text("Date: " + date,20,95);


// Summary

doc.text("Calculation Summary:",20,115);


let lines = doc.splitTextToSize(details,170);

doc.text(lines,20,130);


// Footer

doc.text(
"Prepared by The SR Homes",
20,
280
);


// Save PDF

doc.save("The_SR_Homes_Engineering_Report.pdf");

}
